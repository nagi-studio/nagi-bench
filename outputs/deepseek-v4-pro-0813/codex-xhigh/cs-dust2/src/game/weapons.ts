export function createLoadout(team: Team, pistolRound: boolean): {
  primary: WeaponId | null;
  secondary: WeaponId;
  melee: WeaponId;
  armor: number;
  ammo: Partial<Record<WeaponId, AmmoState>>;
} {
  const primary: WeaponId | null = pistolRound ? null : team === 'CT' ? 'm4a4' : 'ak47';
  const secondary: WeaponId = team === 'CT' ? 'usp' : 'glock';
  return {
    primary,
    secondary,
    melee: 'knife',
    armor: pistolRound ? 0 : 100,
    ammo: {
      [secondary]: { mag: WEAPON_DEFS[secondary].magSize, reserve: WEAPON_DEFS[secondary].reserveMax },
      ...(primary
        ? { [primary]: { mag: WEAPON_DEFS[primary].magSize, reserve: WEAPON_DEFS[primary].reserveMax } }
        : {}),
    },
  };
}

export function freshAmmo(id: WeaponId): AmmoState {
  return { mag: WEAPON_DEFS[id].magSize, reserve: WEAPON_DEFS[id].reserveMax };
}
