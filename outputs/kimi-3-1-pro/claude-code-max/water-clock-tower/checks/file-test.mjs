import { chromium } from 'playwright-core';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const browser = await chromium.launch({ executablePath: '/opt/agentbench/browser/chromium_headless_shell-1228/chrome-linux/headless_shell', chromiumSandbox: false, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--disable-dev-shm-usage','--autoplay-policy=no-user-gesture-required'] });
const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, offline: true });
const page = await context.newPage();
const errors = [], network = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
page.on('request', r => { if (/^https?:/.test(r.url())) network.push(r.url()); });
await page.goto(pathToFileURL(resolve('dist/index.html')).href, { waitUntil: 'load' });
await page.waitForFunction(() => window.__film?.ready, null, { timeout: 120000 });
const initial = await page.evaluate(() => ({time:__film.time, stats:__film.stats()}));
await page.click('#pause');
const pausedAt = await page.evaluate(() => __film.time);
await page.waitForTimeout(400);
const pausedAfter = await page.evaluate(() => __film.time);
await page.click('#sound');
const soundText = await page.locator('#sound').innerText();
await page.keyboard.press('Space');
await page.waitForFunction(t => window.__film.time > t, pausedAt, { timeout: 15000 });
const resumedAt = await page.evaluate(() => __film.time);
await page.keyboard.press('KeyR');
await page.waitForFunction(() => window.__film?.ready && window.__film.time < 3, null, { timeout: 120000 });
const replayTime = await page.evaluate(() => __film.time);
console.log(JSON.stringify({ fileOfflineReady: true, initialTime: initial.time, bodies: initial.stats.bodies, strikes: initial.stats.strikes, pausedAt, pausedAfter, resumedAt, replayTime, soundText, errors, network }, null, 2));
await browser.close();
if (errors.length || network.length || pausedAfter !== pausedAt || resumedAt <= pausedAt) throw new Error('Offline playback check failed');
